"""Render pytest-playwright Page Object code from an approved test plan (T-013, ADR-008, ADR-021).

Deterministic: no model call happens here. The model's contribution ended with the structured
plan (T-012). Every locator comes from the inspector's verified default locator of the element
the plan cites, so generated code cannot contain an invented selector.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any
from urllib.parse import urlsplit

from gatp.inspector.locators import LocatorSpec
from gatp.test_designer.plan import Expectation, PlanStep, TestCase, TestPlan

HEADER = (
    "# Generated by GATP from test plan v{plan_number} (version id {plan_version_id}).\n"
    "# Locators come only from the inspection snapshot; edits in GATP create new versions.\n"
)


@dataclass(frozen=True)
class ElementRef:
    """What codegen needs to know about a cited element."""

    id: str  # s2.e4
    page_url: str
    role: str
    tag: str
    name: str
    html_id: str
    locator: LocatorSpec  # verified default locator


@dataclass(frozen=True)
class GeneratedFile:
    path: str  # e.g. pages/add_page.py
    kind: str  # page_object | test_file
    content: str


def slug(text: str, default: str = "item") -> str:
    s = re.sub(r"[^a-zA-Z0-9]+", "_", text).strip("_").lower()
    if not s:
        return default
    return f"_{s}" if s[0].isdigit() else s


def page_class(url: str) -> tuple[str, str]:
    """(module name, class name) for a page URL, e.g. add.html -> (add_page, AddPage)."""
    path = urlsplit(url).path.strip("/") or "index"
    base = slug(path.rsplit(".", 1)[0].replace("/", "_"), "index")
    return f"{base}_page", "".join(p.capitalize() for p in base.split("_")) + "Page"


def attribute_name(ref: ElementRef, taken: set[str]) -> str:
    kind = {
        "textbox": "input",
        "searchbox": "search",
        "combobox": "select",
        "button": "button",
    }.get(ref.role, ref.role or ref.tag)
    base = slug(f"{ref.name or ref.html_id or ref.id}_{kind}", "element")
    name, n = base, 2
    while name in taken:
        name, n = f"{base}_{n}", n + 1
    taken.add(name)
    return name


def _q(text: str) -> str:
    return repr(text)


def render(
    plan: TestPlan,
    elements: dict[str, ElementRef],
    *,
    origin: str,
    plan_number: int,
    plan_version_id: int,
    setups: dict[str, list[dict[str, Any]]] | None = None,
) -> list[GeneratedFile]:
    """All files for the plan: one page object per page used, the tests, and conftest.py."""
    header = HEADER.format(plan_number=plan_number, plan_version_id=plan_version_id)
    used: dict[str, list[ElementRef]] = {}
    pages: set[str] = set()
    for case in plan.cases:
        for step in case.steps:
            if step.action == "goto":
                pages.add(step.value)
            elif step.element_id:
                _use(used, elements[step.element_id])
        for exp in case.expected:
            if exp.element_id:
                _use(used, elements[exp.element_id])
    pages |= set(used)
    names: dict[str, str] = {}  # element id -> "<module>.<attribute>"
    files: list[GeneratedFile] = []
    for url in sorted(pages):
        module, cls = page_class(url)
        taken: set[str] = {"page", "url", "open", "base_url"}
        lines = [
            header,
            '"""Page object for ' + url + ' (GATP)."""',
            "",
            "from playwright.sync_api import Page",
            "",
            "",
            f"class {cls}:",
            f'    """{urlsplit(url).path or "/"}: locators verified by GATP inspection."""',
            "",
            f"    PATH = {_q(urlsplit(url).path or '/')}",
            "",
            "    def __init__(self, page: Page, base_url: str) -> None:",
            "        self.page = page",
            "        self.base_url = base_url",
            "        self.url = base_url + self.PATH",
        ]
        for ref in sorted(used.get(url, []), key=lambda r: _sort_key(r.id)):
            attr = attribute_name(ref, taken)
            names[ref.id] = f"{module}.{attr}"
            label = (
                repr(ref.name) if ref.name else f"#{ref.html_id}" if ref.html_id else "(unnamed)"
            )
            lines.append(f"        # {ref.id}: {ref.role or ref.tag} {label}")
            lines.append(f"        self.{attr} = {ref.locator.to_python('page')}")
        lines += ["", "    def open(self) -> None:"]
        steps = (setups or {}).get(url, [])
        if steps:
            lines.append(
                '        """Tester-approved setup steps for this page (ADR-018), then the page."""'
            )
            lines.append("        page = self.page")
            lines += [_setup_line(step) for step in steps]
        lines += ["        self.page.goto(self.url)", ""]
        files.append(GeneratedFile(f"pages/{module}.py", "page_object", "\n".join(lines)))
    files.append(GeneratedFile("pages/__init__.py", "page_object", header))
    files.append(_tests_file(plan, header, names, origin))
    files.append(_conftest(header, origin))
    return files


def _setup_line(step: dict[str, Any]) -> str:
    """One setup step as code; goto URLs keep only their path (base URL set per run)."""
    action = step["action"]
    if action == "goto":
        path = urlsplit(step["url"]).path or "/"
        return f"        page.goto(self.base_url + {_q(path)})"
    target = LocatorSpec.model_validate(step["locator"]).to_python("page")
    value = step.get("value", "")
    if action == "fill":
        return f"        {target}.fill({_q(value)})"
    if action == "select":
        return f"        {target}.select_option({_q(value)})"
    return f"        {target}.click()"


def _use(used: dict[str, list[ElementRef]], ref: ElementRef) -> None:
    bucket = used.setdefault(ref.page_url, [])
    if ref not in bucket:
        bucket.append(ref)


def _sort_key(element_id: str) -> tuple[str, int]:
    tail = element_id.rsplit(".", 1)[-1]
    return tail[0], int(tail[1:]) if tail[1:].isdigit() else 0


def _tests_file(plan: TestPlan, header: str, names: dict[str, str], origin: str) -> GeneratedFile:
    modules = sorted(
        {n.split(".")[0] for n in names.values()} | {page_class(u)[0] for u in _goto_urls(plan)}
    )
    lines = [
        header,
        '"""Tests generated from the approved test plan (one function per test case)."""',
        "",
        "import re",
        "",
        "from playwright.sync_api import Page, expect",
        "",
    ]
    lines += [f"from pages.{m} import {_class_of(m)}" for m in modules]
    for case in plan.cases:
        lines += ["", "", *_test_function(case, names)]
    lines.append("")
    # `re` is only needed for URL checks; keep the import tidy for review.
    content = "\n".join(lines)
    if "re.compile" not in content:
        content = content.replace("import re\n\n", "", 1)
    return GeneratedFile("tests/test_plan.py", "test_file", content)


def _class_of(module: str) -> str:
    return "".join(p.capitalize() for p in module.removesuffix("_page").split("_")) + "Page"


def _goto_urls(plan: TestPlan) -> set[str]:
    return {s.value for c in plan.cases for s in c.steps if s.action == "goto"}


def _test_function(case: TestCase, names: dict[str, str]) -> list[str]:
    fname = f"test_{slug(case.id)}_{slug(case.title)}"[:80]
    doc = [f'    """{case.id}: {case.title}', "", f"    Priority: {case.priority}."]
    for pre in case.preconditions:
        doc.append(f"    Precondition: {pre}")
    doc.append("    Expected results (basis):")
    doc += [f"      {e.id}: {e.kind} [{_basis(e)}] {e.evidence}" for e in case.expected]
    doc.append('    """')
    body = [f"def {fname}(page: Page, base_url: str) -> None:", *doc]
    objects: dict[str, str] = {}

    def obj(module: str) -> str:
        if module not in objects:
            var = module.removesuffix("_page") + "_page"
            objects[module] = var
            body.append(f"    {var} = {_class_of(module)}(page, base_url)")
        return objects[module]

    for step in case.steps:
        body.append(_step_line(step, names, obj))
    for exp in case.expected:
        body.append(_expect_line(exp, names, obj))
    return body


def _basis(exp: Expectation) -> str:
    return (
        "assumption, confirmed by tester"
        if exp.basis == "assumption" and exp.confirmed
        else exp.basis
    )


def _target(element_id: str | None, names: dict[str, str], obj: Any) -> str:
    module, attr = names[element_id or ""].split(".")
    return f"{obj(module)}.{attr}"


def _step_line(step: PlanStep, names: dict[str, str], obj: Any) -> str:
    if step.action == "goto":
        return f"    {obj(page_class(step.value)[0])}.open()"
    target = _target(step.element_id, names, obj)
    if step.action == "fill":
        return f"    {target}.fill({_q(step.value)})"
    if step.action == "select":
        return f"    {target}.select_option({_q(step.value)})"
    if step.action == "press":
        return f"    {target}.press({_q(step.value)})"
    return f"    {target}.{step.action}()"  # click / check / uncheck


def _expect_line(exp: Expectation, names: dict[str, str], obj: Any) -> str:
    comment = f"  # {exp.id} [{_basis(exp)}]"
    if exp.kind == "url_contains":
        return f"    expect(page).to_have_url(re.compile(re.escape({_q(exp.value)}))){comment}"
    target = _target(exp.element_id, names, obj)
    assertion = {
        "visible": "to_be_visible()",
        "hidden": "to_be_hidden()",
        "enabled": "to_be_enabled()",
        "disabled": "to_be_disabled()",
        "checked": "to_be_checked()",
        "text_equals": f"to_have_text({_q(exp.value)})",
        "text_contains": f"to_contain_text({_q(exp.value)})",
        "value_equals": f"to_have_value({_q(exp.value)})",
        "count_equals": f"to_have_count({int(exp.value) if exp.value.isdigit() else 0})",
    }[exp.kind]
    return f"    expect({target}).{assertion}{comment}"


def _conftest(header: str, origin: str) -> GeneratedFile:
    content = "\n".join(
        [
            header,
            '"""Shared settings for the generated tests."""',
            "",
            "import os",
            "",
            "import pytest",
            "",
            "",
            '@pytest.fixture(scope="session")',
            "def base_url() -> str:",
            '    """The approved target origin (the runner sets GATP_BASE_URL for each run)."""',
            f'    return os.environ.get("GATP_BASE_URL", {_q(origin)})',
            "",
            "",
            '@pytest.fixture(scope="session")',
            "def browser_type_launch_args(browser_type_launch_args: dict) -> dict:",
            '    """Visible browser unless GATP_HEADLESS=1; optional Chromium path from GATP."""',
            "    args = dict(browser_type_launch_args)",
            '    args["headless"] = os.environ.get("GATP_HEADLESS", "0") == "1"',
            '    if os.environ.get("GATP_CHROMIUM_EXECUTABLE"):',
            '        args["executable_path"] = os.environ["GATP_CHROMIUM_EXECUTABLE"]',
            "    return args",
            "",
        ]
    )
    return GeneratedFile("conftest.py", "test_file", content)
